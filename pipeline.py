import csv
import sqlite3


def extract(csv_path="data/customers.csv"):
    """
    Read raw rows from the CSV file.

    Returns:
        A list of dictionaries, where each dictionary represents
        one customer record from the CSV file.
    """
    rows = []

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)

        for row in reader:
            rows.append(dict(row))

    return rows


def transform(rows: list[dict]) -> list[dict]:
    """
    Clean raw rows and return a list of validated customer records.

    Transformation rules:
    1. Strip whitespace from email and convert it to lowercase.
    2. Skip records whose email does not contain '@'.
    3. Convert status to lowercase.
    4. Convert signup_year to an integer.
    5. Skip records whose signup_year cannot be converted to int.
    """

    records = []

    for row in rows:

        # ---------------------------------------------------------
        # TASK 1A:
        # Clean the email address.
        #
        # Example:
        # "  Priya@Example.COM  "
        #
        # becomes:
        # "priya@example.com"
        # ---------------------------------------------------------
        email = row["email"].strip().lower()

        # ---------------------------------------------------------
        # TASK 1B:
        # Validate the email.
        #
        # The assessment only requires checking whether the email
        # contains "@". If it does not, skip this entire row.
        # ---------------------------------------------------------
        if "@" not in email:
            continue

        # ---------------------------------------------------------
        # TASK 1C:
        # Normalize customer status to lowercase.
        #
        # Examples:
        # "Active"   -> "active"
        # "ACTIVE"   -> "active"
        # "INACTIVE" -> "inactive"
        # ---------------------------------------------------------
        status = row["status"].lower()

        # ---------------------------------------------------------
        # TASK 1D:
        # Convert signup_year from the CSV string into an integer.
        #
        # Examples:
        # "2021" -> 2021
        #
        # Invalid values such as:
        # "N/A"
        # "abc"
        #
        # cannot be converted to int, so those records must
        # be skipped.
        # ---------------------------------------------------------
        try:
            signup_year = int(row["signup_year"])
        except (ValueError, TypeError):
            continue

        # ---------------------------------------------------------
        # If the record passed all validation rules, add the
        # cleaned record to the final list.
        #
        # name and country are preserved as provided.
        # ---------------------------------------------------------
        records.append(
            {
                "name": row["name"],
                "email": email,
                "country": row["country"],
                "status": status,
                "signup_year": signup_year,
            }
        )

    return records


def load(records: list[dict], db_path: str = "customers.db") -> None:
    """
    Insert the transformed records into the customers table.

    The task requires replacing the existing customer data with
    the newly transformed records.
    """

    # Open a connection to the SQLite database.
    conn = sqlite3.connect(db_path)

    # Create a cursor used to execute SQL commands.
    cursor = conn.cursor()

    # ---------------------------------------------------------
    # The starter code already clears existing records.
    #
    # This ensures that running load() replaces the old data
    # instead of continuously appending duplicate records.
    # ---------------------------------------------------------
    cursor.execute("DELETE FROM customers")

    # ---------------------------------------------------------
    # TASK 2:
    # Bulk-insert all transformed records.
    #
    # executemany() is used because records is a list of
    # dictionaries.
    #
    # The :name, :email, etc. placeholders correspond to the
    # dictionary keys generated by transform().
    # ---------------------------------------------------------
    cursor.executemany(
        """
        INSERT INTO customers (
            name,
            email,
            country,
            status,
            signup_year
        )
        VALUES (
            :name,
            :email,
            :country,
            :status,
            :signup_year
        )
        """,
        records,
    )

    # Save the changes.
    conn.commit()

    # Close the database connection.
    conn.close()


# -------------------------------------------------------------
# Run the complete ETL pipeline when this file is executed
# directly:
#
# python3 pipeline.py
#
# Extract -> Transform -> Load
# -------------------------------------------------------------
if __name__ == "__main__":

    # Extract raw customer data from:
    # data/customers.csv
    rows = extract()

    # Clean and validate the raw records.
    records = transform(rows)

    # Replace the customer records in customers.db.
    load(records)

    # Display the number of valid records loaded.
    print(f"Loaded {len(records)} records into customers.db")